_PARTS = LATEX_DIR / "tables.json"


def table(name: str, body: str) -> None:
    """Record a table part and re-render every complete ``tab_*.tex`` file.

    ``body`` is complete rows (``\\\\`` line ends). Parts are stored in
    ``tables.json``; each spec in ``_TABLES`` composes its parts into a full
    tabular environment, written as ``tab_<spec>.tex`` once all parts exist.
    """
    if not _KEY.fullmatch(name):
        raise ValueError(f"table name must be alphabetic: {name!r}")
    LATEX_DIR.mkdir(parents=True, exist_ok=True)
    parts = json.loads(_PARTS.read_text()) if _PARTS.exists() else {}
    parts[name] = body
    _PARTS.write_text(json.dumps(parts, indent=1, sort_keys=True))
    for out, spec in _TABLES.items():
        if not all(p in parts for p in spec["parts"]):
            continue
        rows = "\\midrule\n".join(parts[p] for p in spec["parts"])
        tex = (
            _HEADER
            + f"\\begin{{tabular}}{{{spec['cols']}}}\n\\toprule\n{spec['header']}\n"
            + f"\\midrule\n{rows}\\botrule\n\\end{{tabular}}\n"
        )
        (LATEX_DIR / f"tab_{out}.tex").write_text(tex)


def value(key: str, default: str = "") -> str:
    """Read a recorded value back from the ledger (for figures that display
    quantities computed elsewhere, e.g. the rate's cluster-bootstrap CI)."""
    if not _JSON.exists():
        return default
    return json.loads(_JSON.read_text()).get(key, default)


def pt(x: float, nd: int = 2) -> str:
    """Format a point estimate to ``nd`` decimals."""
    return f"{x:.{nd}f}"


def ci(lo: float, hi: float, nd: int = 2) -> str:
    """Format an interval as ``lo--hi`` to ``nd`` decimals."""
    return f"{lo:.{nd}f}--{hi:.{nd}f}"
