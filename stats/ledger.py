"""
Manuscript number ledger — the single wiring point between the stats scripts
and the LaTeX manuscript.

Every headline quantity the manuscript quotes is ``record()``-ed by the stats
script that computes it, at the point of computation. The ledger accumulates
in ``paper/latex/numbers.json`` and renders to ``paper/latex/numbers.tex`` as
``\\nepi<Key>`` macros, which ``main.tex`` and ``extended_data.tex`` use in
place of typed literals. Whole table bodies are written as
``paper/latex/tab_<name>.tex`` fragments and ``\\input`` by the manuscript.

Regenerating the numbers is therefore the same action as regenerating the
results: run the stats scripts, then recompile the manuscript. A hand-typed
number in the manuscript is a bug.

Policy: the ledger covers model outputs (ratios, intervals, elasticities,
shares, sample sizes). Definitional constants (distance bands, trip rate) and
deliberately approximate prose ("about 2,500 miles") stay in the text.
"""

from __future__ import annotations

import json
import re

from urban_energy.paths import PROJECT_DIR

LATEX_DIR = PROJECT_DIR / "paper" / "latex"
_JSON = LATEX_DIR / "numbers.json"
_TEX = LATEX_DIR / "numbers.tex"

_KEY = re.compile(r"[a-zA-Z]+")

_HEADER = (
    "% Generated by the stats scripts via stats/ledger.py — do not edit.\n"
    "% Regenerate by running the stats scripts (see paper/submission_checklist.md).\n"
)

# Rounded prose variants derived from recorded keys at render time, so the
# approximate forms ("about 27 times", "a 2.1x gap") stay wired to the same
# source as the precise ones. {derived key: (source key, decimals)}.
_DERIVED: dict[str, tuple[str, int]] = {
    "walkAmenRound": ("walkAmen", 0),
    "driveAmenRound": ("driveAmen", 0),
    "totalGapRound": ("totalGap", 1),
}


def record(**kv: str | float | int) -> None:
    """Record named manuscript numbers and re-render ``numbers.tex``.

    Keys must be alphabetic (they become LaTeX macro names ``\\nepi<Key>``).
    Values are stored as strings exactly as they should appear in prose.
    """
    data = json.loads(_JSON.read_text()) if _JSON.exists() else {}
    for key, value in kv.items():
        if not _KEY.fullmatch(key):
            raise ValueError(f"ledger key must be alphabetic: {key!r}")
        data[key] = str(value)
    LATEX_DIR.mkdir(parents=True, exist_ok=True)
    _JSON.write_text(json.dumps(data, indent=1, sort_keys=True))
    rendered = dict(data)
    for derived, (source, nd) in _DERIVED.items():
        if source in rendered:
            rendered[derived] = f"{float(rendered[source]):.{nd}f}"
    tex = _HEADER + "".join(
        f"\\newcommand{{\\nepi{k}}}{{{v}}}\n" for k, v in sorted(rendered.items())
    )
    _TEX.write_text(tex)


#: Rendered table specifications. Each output ``tab_<file>.tex`` is a COMPLETE
